// TestRegisterPagesOverTheSheetFixture: the sheet fixture renders the root
// page, holding its work, and one page per volume hosting a node — alpha's
// and beta's, gamma hosting none. Each entry's heading slug is its node's
// canonical anchor on that page, every node whose canonical path is a page has
// its entry there, and every link a page renders resolves. The fixture is
// converted and saved on a copy, since the dead-link gate finds a link's file
// on disk.
func TestRegisterPagesOverTheSheetFixture(t *testing.T) {
	root := filepath.Join(t.TempDir(), "repo", kb.KBDir)
	if err := os.CopyFS(root, os.DirFS(sheetFixtureKB)); err != nil {
		t.Fatal(err)
	}
	converted, err := kbload.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	if _, _, _, err := UpdateFormat(converted, nil, nil, log.Discard()); err != nil {
		t.Fatal(err)
	}
	src := kb.OnDisk(root)
	pages, err := renderRegisterPages(src)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"alpha/" + kb.RegisterFile, "beta/" + kb.RegisterFile, kb.RegisterFile}
	if got := slices.Sorted(maps.Keys(pages)); !slices.Equal(got, want) {
		t.Fatalf("pages %q, want %q", got, want)
	}
	rows, err := Derive(src)
	if err != nil {
		t.Fatal(err)
	}
	onPage := map[string]map[string]string{} // page → node id → the anchor its heading takes
	for rel, data := range pages {
		onPage[rel] = headingMarkerAnchors(string(data))
	}
	for _, n := range rows.Nodes {
		if _, isPage := pages[n.CanonicalPath]; !isPage {
			continue
		}
		if slug, ok := onPage[n.CanonicalPath][n.ID]; !ok || slug != n.CanonicalAnchor {
			t.Errorf("%s's entry on %s has slug %q (present %v), want its canonical anchor %q", n.ID, n.CanonicalPath, slug, ok, n.CanonicalAnchor)
		}
	}
	x, err := loadDerivation(src)
	if err != nil {
		t.Fatal(err)
	}
	dead, err := kb.DeadLinksIn(src, src.Repo(), x.pageSlugs())
	if err != nil {
		t.Fatal(err)
	}
	for _, d := range dead {
		if _, isPage := pages[d.File]; isPage {
			t.Errorf("a rendered page's link does not resolve: %s", d)
		}
	}
}

// headingMarkerAnchors is, for each node whose marker ends a heading of a
// page, a work's included, the anchor GitHub's slugger gives that heading
// among the page's.
func headingMarkerAnchors(page string) map[string]string {
	out := map[string]string{}
	lines := kb.SplitLines(page)
	for i, anchor := range kb.HeadingAnchors(page) {
		for _, m := range kb.StatementMarkerRE.FindAllStringSubmatch(lines[i], -1) {
			out[m[1]] = anchor
		}
	}
	return out
}

// TestRegisterPageHeadAndEntries: a page opens with its title and its one-line
// preamble, each entry is headed by its title carrying its node's marker, the
// claim's entry first where its marker is read first on the line it shares
// with its analysis's, and an entry's anchor is its heading's among every
// heading of the page — the analysis sharing the claim's title, and a title
// the page's own section headings already took, take a suffix.
func TestRegisterPageHeadAndEntries(t *testing.T) {
	g := kb.Graph{
		Claims:   []kb.ClaimNode{{ID: "clm-aaaaaa", Title: "Cure Is Hard"}, {ID: "clm-bbbbbb", Title: "Rigor"}},
		Analyses: []kb.AnalysisNode{{ID: "ana-aaaaaa", Title: "Cure Is Hard"}},
	}
	src := graphKB(t, g, map[string]string{
		kb.EntryPointFile: "# KB\n\n- [leaf](leaf.md)\n",
		"leaf.md":         "[↑ KB](entry-point.md)\n\n# Cure Is Hard" + kb.StatementMarker("clm-aaaaaa") + kb.StatementMarker("ana-aaaaaa") + "\n\nRigor." + kb.StatementMarker("clm-bbbbbb") + "\n",
	})
	pages, err := renderRegisterPages(src)
	if err != nil {
		t.Fatal(err)
	}
	page := string(pages[kb.RegisterFile])
	if head := "# KB summary\n\nGenerated by kbase from the KB's records; do not edit.\n\n## Cure Is Hard<!-- kbase-id: clm-aaaaaa -->\n"; !strings.HasPrefix(page, head) {
		t.Errorf("the page opens\n%s\nwant it to open\n%s", page, head)
	}
	for _, heading := range []string{"## Cure Is Hard<!-- kbase-id: clm-aaaaaa -->\n", "## Cure Is Hard<!-- kbase-id: ana-aaaaaa -->\n",
		"## Rigor<!-- kbase-id: clm-bbbbbb -->\n"} {
		if !strings.Contains(page, "\n"+heading) {
			t.Errorf("the page holds no entry headed %q:\n%s", heading, page)
		}
	}
	want := map[string]string{"clm-aaaaaa": "cure-is-hard", "ana-aaaaaa": "cure-is-hard-1", "clm-bbbbbb": "rigor-2"}
	if got := headingMarkerAnchors(page); !maps.Equal(got, want) {
		t.Errorf("the page's headings anchor %v, want %v", got, want)
	}
	rows, err := Derive(src)
	if err != nil {
		t.Fatal(err)
	}
	for _, n := range rows.Nodes {
		if n.NodeType == kb.NodeKindClaim && n.CanonicalAnchor != want[n.ID] {
			t.Errorf("%s's canonical anchor %q, want %q", n.ID, n.CanonicalAnchor, want[n.ID])
		}
	}
}

// TestRegisterPagesOrderEntries: a page's hosted nodes come in reading order
// of their marker — the host's place in the spine walk, not its path, then the
// marker's line — and the root page's works by label, whatever their minted
// ids' order.
func TestRegisterPagesOrderEntries(t *testing.T) {
	g := kb.Graph{
		Claims: []kb.ClaimNode{{ID: "clm-aaaaaa", Title: "A"}, {ID: "clm-bbbbbb", Title: "B"}, {ID: "clm-cccccc", Title: "C"}},
		Works:  []kb.WorkNode{{ID: "wrk-a00000", Label: "zed2020", Title: "Zed"}, {ID: "wrk-z00000", Label: "abe2020", Title: "Abe"}},
	}
	x, err := loadDerivation(graphKB(t, g, map[string]string{
		kb.EntryPointFile: "# KB\n\n- [v](v/index.md)\n",
		"v/index.md":      "[↑ KB](../entry-point.md)\n\n# V\n\n- [z](z.md)\n- [a](a.md)\n",
		"v/z.md":          "[↑ V](index.md)\n\n# Z\n\nB. <!-- kbase-id: clm-bbbbbb -->\n\nA. <!-- kbase-id: clm-aaaaaa -->\n",
		"v/a.md":          "[↑ V](index.md)\n\n# A\n\nC. <!-- kbase-id: clm-cccccc -->\n",
	}))
	if err != nil {
		t.Fatal(err)
	}
	entries := x.pageEntries()
	if got, want := entries["v/"+kb.RegisterFile], []string{"clm-bbbbbb", "clm-aaaaaa", "clm-cccccc"}; !slices.Equal(got, want) {
		t.Errorf("v's page orders %q, want %q", got, want)
	}
	if got, want := entries[kb.RegisterFile], []string{"wrk-z00000", "wrk-a00000"}; !slices.Equal(got, want) {
		t.Errorf("the root page orders %q, want %q", got, want)
	}
}

// TestRegisterFreshnessFaultAndFix: a page called for and missing, a page
// whose bytes differ from what refresh renders, and a page standing in a volume
// no node is rendered on are each a register-freshness finding, remedy the
// empty batch, and a register file in a directory no volume is is none; written as
// rendered, and the uncalled page gone, none is.
func TestRegisterFreshnessFaultAndFix(t *testing.T) {
	files := graphFiles(kb.Graph{
		Claims: []kb.ClaimNode{{ID: "clm-aaaaaa", Title: "Theorem 1", Rigor: f(0.9)}},
		Works:  []kb.WorkNode{{ID: "wrk-k00000", Label: "key2020", Title: "Key 2020", Rigor: f(0.8)}},
		Founds: []kb.BearingEdge{{Source: "wrk-k00000", Target: "clm-aaaaaa", Bearing: kb.Bearing{Value: 1}}},
	})
	for rel, text := range map[string]string{
		kb.EntryPointFile:          "# KB\n\n- [a](a/index.md)\n- [g](g/index.md)\n",
		"a/index.md":               "[↑ KB](../entry-point.md)\n\n# A\n\n- [leaf](leaf.md)\n",
		"a/leaf.md":                "[↑ A](index.md)\n\n# Leaf\n\nA theorem.<!-- kbase-id: clm-aaaaaa -->\n",
		"g/index.md":               "[↑ KB](../entry-point.md)\n\n# G\n",
		"g/" + kb.RegisterFile:     "# KB summary\n",
		"a/" + kb.RegisterFile:     "# KB summary\n\nstale\n",
		"loose/" + kb.RegisterFile: "# In a directory no volume is, so no page\n",
	} {
		files[rel] = text
	}
	root := writeKB(t, files)
	findings := func() []string {
		t.Helper()
		found, err := RegisterFreshness(kb.OnDisk(root))
		if err != nil {
			t.Fatal(err)
		}
		var out []string
		for _, f := range found {
			if f.Check != CheckRegisterFreshness || f.Remedy != EmptyBatchRemedy {
				t.Errorf("%+v is not a %s finding whose remedy is the empty batch", f, CheckRegisterFreshness)
			}
			out = append(out, f.Detail)
		}
		return out
	}
	want := []string{
		"a/" + kb.RegisterFile + " is not as kbase renders it",
		"g/" + kb.RegisterFile + " stands, and no node is rendered on it",
		kb.RegisterFile + " is missing",
	}
	if got := findings(); !slices.Equal(got, want) {
		t.Errorf("RegisterFreshness =\n%q\nwant\n%q", got, want)
	}
	pages, err := renderRegisterPages(kb.OnDisk(root))
	if err != nil {
		t.Fatal(err)
	}
	for rel, data := range pages {
		if err := os.WriteFile(filepath.Join(root, filepath.FromSlash(rel)), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Remove(filepath.Join(root, "g", kb.RegisterFile)); err != nil {
		t.Fatal(err)
	}
	if got := findings(); len(got) != 0 {
		t.Errorf("RegisterFreshness after the fix = %q, want none", got)
	}
}
